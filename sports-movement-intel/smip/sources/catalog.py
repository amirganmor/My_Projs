"""Data catalog: merges the static registry with discovered facts into a manifest lock + DATA_SOURCES.md.

Discovered facts come only from files on disk (assets.jsonl written by the downloader and the
normalized match.json / corpus.json files written by adapters). Nothing here is hand-entered.
"""

from __future__ import annotations

import json
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

from smip.config import REPO_ROOT, get_settings
from smip.sources.fetch import file_digest, load_asset_index
from smip.sources.registry import load_registry

MANIFEST = "manifest.lock.json"


def _catalog_dir() -> Path:
    return get_settings().data_dir / "catalog"


def verify_assets() -> dict:
    """Re-hash every recorded raw asset; compare with its recorded sha256 and publisher checksum."""
    s = get_settings()
    idx = load_asset_index(_catalog_dir())
    ok, mismatched, missing, details = 0, 0, 0, []
    for rel, rec in sorted(idx.items()):
        p = s.raw_dir / rel
        if not p.exists():
            missing += 1
            details.append({"path": rel, "status": "missing"})
            continue
        digest = file_digest(p, "sha256")
        good = digest == rec.sha256
        if good and rec.expected_checksum and rec.checksum_algo:
            good = (digest if rec.checksum_algo == "sha256" else file_digest(p, rec.checksum_algo)) == rec.expected_checksum
        if good:
            ok += 1
        else:
            mismatched += 1
            details.append({"path": rel, "status": "mismatch"})
    return {"verified": ok, "mismatched": mismatched, "missing": missing, "details": details}


def _normalized(source: str) -> tuple[list[dict], dict | None]:
    root = get_settings().normalized_dir / source
    matches, corpus = [], None
    if not root.exists():
        return matches, corpus
    cp = root / "corpus.json"
    if cp.exists():
        corpus = json.loads(cp.read_text())
    for mj in sorted(root.glob("*/match.json")):
        m = json.loads(mj.read_text())
        q = mj.with_name("quality.json")
        matches.append({
            "match_id": m["match_id"], "competition": m.get("competition"), "season": m.get("season"),
            "date": m.get("date"), "home": m["home_team"]["name"], "away": m["away_team"]["name"],
            "sample_rate_hz": m.get("sample_rate_hz"), "counts": m.get("counts"),
            "quality": json.loads(q.read_text()) if q.exists() else None,
        })
    return matches, corpus


def build_catalog(write_docs: bool = False) -> dict:
    reg = load_registry()
    idx = load_asset_index(_catalog_dir())
    by_src: dict[str, list] = defaultdict(list)
    for rec in idx.values():
        by_src[rec.source].append(rec)
    out = {"generated_at": datetime.now(timezone.utc).isoformat(), "sources": {}}
    for name, src in reg["sources"].items():
        recs = by_src.get(name, [])
        matches, corpus = _normalized(name)
        out["sources"][name] = {
            "publisher": src.get("publisher"), "sport": src.get("sport"), "priority": src.get("priority"),
            "url": src.get("url"), "pinned_revision": src.get("pinned_revision"),
            "access_status": src.get("access_status"), "data_license": src.get("data_license"),
            "code_license": src.get("code_license"), "redistributable_demo": bool(src.get("redistributable_demo")),
            "capabilities": src.get("capabilities"), "sample_rate_hz": src.get("sample_rate_hz"),
            "units": src.get("units"),
            "downloaded_assets": len(recs), "downloaded_bytes": sum(r.size_bytes for r in recs),
            "revisions_on_disk": sorted({r.revision for r in recs}),
            "first_retrieved_at": min((r.retrieved_at for r in recs), default=None),
            "last_retrieved_at": max((r.retrieved_at for r in recs), default=None),
            "publisher_checksums": sum(1 for r in recs if r.expected_checksum),
            "normalized_matches": len(matches), "corpus": corpus, "matches": matches,
            "assets": [{"path": r.local_path, "bytes": r.size_bytes, "sha256": r.sha256, "url": r.url} for r in
                       sorted(recs, key=lambda r: r.local_path)],
        }
    cdir = _catalog_dir()
    cdir.mkdir(parents=True, exist_ok=True)
    (cdir / MANIFEST).write_text(json.dumps(out, indent=2, default=str))
    if write_docs:
        (REPO_ROOT / "docs").mkdir(exist_ok=True)
        (REPO_ROOT / "docs" / "DATA_SOURCES.md").write_text(render_markdown(out, reg))
    return out


def load_catalog() -> dict:
    p = _catalog_dir() / MANIFEST
    return json.loads(p.read_text()) if p.exists() else build_catalog()


def _mb(n: int) -> str:
    return f"{n / 1e6:,.1f} MB"


def render_markdown(cat: dict, reg: dict) -> str:
    L = ["# Data sources", "",
         "_Generated by `smip sources catalog` from `config/sources.yaml` (reviewed facts) and files on disk "
         "(discovered facts). Do not hand-edit; edit the registry and regenerate._", "",
         f"Generated at: {cat['generated_at']}", "",
         "Every replay of these datasets is a **historical match replay**. No source is a live feed.", "",
         "## Summary", "",
         "| source | sport | priority | access | data license | public demo | assets on disk | size | normalized matches |",
         "|---|---|---|---|---|---|---|---|---|"]
    for name, s in cat["sources"].items():
        L.append(f"| {name} | {s['sport']} | {s['priority']} | {s['access_status']} | {s['data_license']} | "
                 f"{'yes' if s['redistributable_demo'] else 'no'} | {s['downloaded_assets']} | "
                 f"{_mb(s['downloaded_bytes'])} | {s['normalized_matches']} |")
    L += ["", "`public demo = no` sources are usable locally for research but are excluded from the default "
          "redistributable demo (screenshots, YouTube). A downloader's software license never implies a data license.",
          ""]
    caps = ["continuous_tracking", "ball_coordinates", "ball_height", "event_coordinates", "snapshots", "identity",
            "outcomes", "pose", "footage", "detection_flag"]
    L += ["## Capability matrix", "", "| source | " + " | ".join(caps) + " |", "|---" * (len(caps) + 1) + "|"]
    for name, s in cat["sources"].items():
        c = s.get("capabilities") or {}
        L.append(f"| {name} | " + " | ".join(str(c.get(k, "n/a")) for k in caps) + " |")
    L.append("")
    for name, s in cat["sources"].items():
        src = reg["sources"][name]
        L += [f"## {name}", "", f"- Publisher: {s['publisher']}", f"- URL: {s['url']}",
              f"- Pinned revision: `{s['pinned_revision']}`" if s["pinned_revision"] else "- Pinned revision: n/a",
              f"- Access status: `{s['access_status']}`", f"- Data license: {s['data_license']}",
              f"- Code license: {s['code_license']}", f"- Attribution: {src.get('attribution', 'n/a')}",
              f"- Redistribution: {src.get('redistribution', 'n/a')}"]
        if s.get("units"):
            L.append(f"- Units: {s['units']}")
        if s["downloaded_assets"]:
            L.append(f"- On disk: {s['downloaded_assets']} files, {_mb(s['downloaded_bytes'])}, retrieved "
                     f"{s['first_retrieved_at']} .. {s['last_retrieved_at']}; "
                     f"{s['publisher_checksums']} with publisher checksums, all with local sha256.")
        if s.get("corpus"):
            L.append(f"- Normalized corpus: `{json.dumps(s['corpus'].get('counts', s['corpus']), default=str)[:400]}`")
        for c in src.get("caveats", []):
            L.append(f"- Caveat: {c}")
        if s["matches"]:
            L += ["", "| match | teams | date | Hz | frames | position rows | events | detected share |",
                  "|---|---|---|---|---|---|---|---|"]
            for m in s["matches"]:
                cnt, q = m.get("counts") or {}, m.get("quality") or {}
                det = q.get("detected_fraction")
                L.append(f"| {m['match_id']} | {m['home']} v {m['away']} | {(m.get('date') or '')[:10]} | "
                         f"{m['sample_rate_hz']} | {cnt.get('frames')} | {cnt.get('position_rows')} | "
                         f"{cnt.get('events')} | {'n/a' if det is None else f'{det:.0%}'} |")
        L.append("")
    return "\n".join(L)
